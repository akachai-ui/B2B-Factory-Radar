export function getCompanyCoordinates(province, district, taxId) {
  let base = null;
  const p = (province || '').trim().replace(/^จ\./, '');
  const d = (district || '').trim().replace(/^(อ\.|เขต)/, '');

  if (p && d && DISTRICT_CENTROIDS[`${p}:${d}`]) {
    base = DISTRICT_CENTROIDS[`${p}:${d}`];
  } else if (p && PROVINCE_CENTROIDS[p]) {
    base = PROVINCE_CENTROIDS[p];
  } else {
    base = PROVINCE_CENTROIDS['กรุงเทพมหานคร'];
  }

  // Deterministic micro jitter based on taxId digits
  const hash = (taxId || '').split('').reduce((acc, ch) => (acc * 31 + ch.charCodeAt(0)) | 0, 0);
  const jitterLat = ((Math.abs(hash) % 1000) - 500) * 0.00004; // +/- ~0.02 deg (~2km)
  const jitterLng = ((Math.abs(hash >> 3) % 1000) - 500) * 0.00004;

  return {
    lat: Number((base.lat + jitterLat).toFixed(6)),
    lng: Number((base.lng + jitterLng).toFixed(6))
  };
}
